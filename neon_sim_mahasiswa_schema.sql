-- SIM Mahasiswa UMB - PostgreSQL / Neon schema
-- Schema-only migration template based on the supplied MySQL/MariaDB dump.
-- Review constraints and test in a separate Neon branch/database before production.
-- This file creates tables and views; it does NOT copy existing MySQL data.

BEGIN;

CREATE TABLE IF NOT EXISTS universitas (
    id_universitas BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_universitas VARCHAR(20) NOT NULL UNIQUE,
    nama_universitas VARCHAR(200) NOT NULL,
    slogan VARCHAR(255),
    alamat TEXT,
    kota VARCHAR(100),
    provinsi VARCHAR(100),
    kode_pos VARCHAR(10),
    website VARCHAR(255),
    email VARCHAR(150),
    telepon VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fakultas (
    id_fakultas BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_universitas BIGINT NOT NULL REFERENCES universitas(id_universitas),
    kode_fakultas VARCHAR(20) NOT NULL,
    nama_fakultas VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_universitas, kode_fakultas)
);

CREATE TABLE IF NOT EXISTS program_studi (
    id_program_studi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fakultas BIGINT NOT NULL REFERENCES fakultas(id_fakultas),
    kode_program_studi VARCHAR(20) NOT NULL,
    nama_program_studi VARCHAR(200) NOT NULL,
    jenjang VARCHAR(20) NOT NULL DEFAULT 'S1',
    status_aktif VARCHAR(20) NOT NULL DEFAULT 'Aktif'
        CHECK (status_aktif IN ('Aktif', 'Tidak Aktif')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_fakultas, kode_program_studi)
);

CREATE TABLE IF NOT EXISTS roles (
    id_role SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_role VARCHAR(30) NOT NULL UNIQUE,
    nama_role VARCHAR(100) NOT NULL,
    keterangan VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pengguna (
    id_pengguna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_role SMALLINT NOT NULL REFERENCES roles(id_role),
    id_universitas BIGINT REFERENCES universitas(id_universitas),
    id_fakultas BIGINT REFERENCES fakultas(id_fakultas),
    id_program_studi BIGINT REFERENCES program_studi(id_program_studi),
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nama_lengkap VARCHAR(200) NOT NULL,
    email VARCHAR(150),
    no_hp VARCHAR(30),
    status_aktif VARCHAR(20) NOT NULL DEFAULT 'Aktif'
        CHECK (status_aktif IN ('Aktif', 'Tidak Aktif')),
    last_login TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mahasiswa (
    id_mahasiswa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna BIGINT UNIQUE REFERENCES pengguna(id_pengguna) ON DELETE SET NULL,
    id_program_studi BIGINT NOT NULL REFERENCES program_studi(id_program_studi),
    npm VARCHAR(30) NOT NULL UNIQUE,
    nama_mahasiswa VARCHAR(200) NOT NULL,
    jenis_kelamin CHAR(1) NOT NULL CHECK (jenis_kelamin IN ('L', 'P')),
    tempat_lahir VARCHAR(100),
    tanggal_lahir DATE,
    tanggal_masuk DATE NOT NULL,
    alamat TEXT,
    status_mahasiswa VARCHAR(30) NOT NULL DEFAULT 'Aktif'
        CHECK (status_mahasiswa IN (
            'Aktif', 'Cuti', 'Lulus', 'Mengundurkan Diri', 'Drop Out', 'Tidak Aktif'
        )),
    -- Store the public/display URL and storage provider key, not the image binary.
    foto_url TEXT,
    foto_storage_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_log (
    id_audit BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna BIGINT REFERENCES pengguna(id_pengguna) ON DELETE SET NULL,
    tabel_nama VARCHAR(100) NOT NULL,
    record_id VARCHAR(100),
    aksi VARCHAR(10) NOT NULL
        CHECK (aksi IN ('LOGIN', 'LOGOUT', 'INSERT', 'UPDATE', 'DELETE', 'VIEW')),
    data_lama JSONB,
    data_baru JSONB,
    ip_address INET,
    user_agent TEXT,
    waktu TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pengguna_role ON pengguna(id_role);
CREATE INDEX IF NOT EXISTS idx_pengguna_universitas ON pengguna(id_universitas);
CREATE INDEX IF NOT EXISTS idx_pengguna_fakultas ON pengguna(id_fakultas);
CREATE INDEX IF NOT EXISTS idx_pengguna_prodi ON pengguna(id_program_studi);
CREATE INDEX IF NOT EXISTS idx_mahasiswa_prodi ON mahasiswa(id_program_studi);
CREATE INDEX IF NOT EXISTS idx_mahasiswa_status ON mahasiswa(status_mahasiswa);
CREATE INDEX IF NOT EXISTS idx_audit_log_pengguna_waktu ON audit_log(id_pengguna, waktu DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_tabel_record ON audit_log(tabel_nama, record_id);

-- Recreate these views after the base tables exist.
CREATE OR REPLACE VIEW v_mahasiswa_per_prodi AS
SELECT
    u.id_universitas, u.kode_universitas, u.nama_universitas,
    f.id_fakultas, f.kode_fakultas, f.nama_fakultas,
    ps.id_program_studi, ps.kode_program_studi, ps.nama_program_studi, ps.jenjang,
    m.id_mahasiswa, m.npm, m.nama_mahasiswa, m.jenis_kelamin,
    CASE m.jenis_kelamin WHEN 'L' THEN 'Laki-laki' WHEN 'P' THEN 'Perempuan' END
        AS jenis_kelamin_text,
    m.tempat_lahir, m.tanggal_lahir, m.tanggal_masuk, m.alamat, m.status_mahasiswa
FROM mahasiswa m
JOIN program_studi ps ON ps.id_program_studi = m.id_program_studi
JOIN fakultas f ON f.id_fakultas = ps.id_fakultas
JOIN universitas u ON u.id_universitas = f.id_universitas;

CREATE OR REPLACE VIEW v_profil_mahasiswa AS
SELECT
    m.id_mahasiswa, m.npm, m.nama_mahasiswa, m.jenis_kelamin,
    m.tempat_lahir, m.tanggal_lahir, m.tanggal_masuk, m.alamat,
    m.status_mahasiswa, m.foto_url, m.foto_storage_key,
    ps.kode_program_studi, ps.nama_program_studi, ps.jenjang,
    f.kode_fakultas, f.nama_fakultas,
    u.kode_universitas, u.nama_universitas
FROM mahasiswa m
JOIN program_studi ps ON ps.id_program_studi = m.id_program_studi
JOIN fakultas f ON f.id_fakultas = ps.id_fakultas
JOIN universitas u ON u.id_universitas = f.id_universitas;

-- Keep updated_at current from PostgreSQL, equivalent to MySQL ON UPDATE behavior.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_universitas_updated_at ON universitas;
CREATE TRIGGER trg_universitas_updated_at BEFORE UPDATE ON universitas
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_fakultas_updated_at ON fakultas;
CREATE TRIGGER trg_fakultas_updated_at BEFORE UPDATE ON fakultas
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_program_studi_updated_at ON program_studi;
CREATE TRIGGER trg_program_studi_updated_at BEFORE UPDATE ON program_studi
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_pengguna_updated_at ON pengguna;
CREATE TRIGGER trg_pengguna_updated_at BEFORE UPDATE ON pengguna
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_mahasiswa_updated_at ON mahasiswa;
CREATE TRIGGER trg_mahasiswa_updated_at BEFORE UPDATE ON mahasiswa
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
